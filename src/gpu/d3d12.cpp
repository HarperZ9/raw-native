bool gpuInit(GpuAdapterInfo& info, std::string& err){ return Device::init(info, err); }

bool renderGpu(const Scene& scene, int w, int h, const Mat4& prevVP,
               const RenderOptions& opts, FrameResult& r, std::string& err, bool frameOnly){
    GpuAdapterInfo info;
    if (!gpuInit(info, err)) return false;
    Device& dev = Device::get();
    const std::vector<float> tris = packTriangles(scene);
    const uint32_t ntri = (uint32_t)(tris.size() / 24), N = (uint32_t)w * (uint32_t)h;
    const Mat4 vp = mul(scene.camera.proj(), scene.camera.view());
    float pf[48] = {};
    packParams(pf, scene, vp, prevVP, w, h, ntri, opts.rtao);
    const uint64_t trisBytes = tris.size() * 4, n4 = N * 4ull, n16 = N * 16ull;
    Frame b;
    bool ok = dev.buffer(d3d12::kParamsBytes + trisBytes, D3D12_HEAP_TYPE_UPLOAD, b.upload, err)
        && dev.buffer(trisBytes, D3D12_HEAP_TYPE_DEFAULT, b.T, err) && dev.buffer(ntri * 64ull, D3D12_HEAP_TYPE_DEFAULT, b.SF, err)
        && dev.buffer(ntri * 16ull, D3D12_HEAP_TYPE_DEFAULT, b.SI, err) && dev.buffer(n4, D3D12_HEAP_TYPE_DEFAULT, b.depth, err)
        && dev.buffer(n16, D3D12_HEAP_TYPE_DEFAULT, b.pos, err) && dev.buffer(n16, D3D12_HEAP_TYPE_DEFAULT, b.nrm, err)
        && dev.buffer(n16, D3D12_HEAP_TYPE_DEFAULT, b.am, err) && dev.buffer(n16, D3D12_HEAP_TYPE_DEFAULT, b.mot, err)
        && dev.buffer(n4, D3D12_HEAP_TYPE_DEFAULT, b.ss, err) && dev.buffer(n4, D3D12_HEAP_TYPE_DEFAULT, b.rt, err)
        && dev.buffer(n16, D3D12_HEAP_TYPE_DEFAULT, b.frame, err) && dev.buffer(n16, D3D12_HEAP_TYPE_DEFAULT, b.hdr, err);
    if (!ok) return false;
    if (!dev.write(b.upload.Get(), 0, pf, sizeof pf, err) || !dev.write(b.upload.Get(), d3d12::kParamsBytes, tris.data(), trisBytes, err)) return false;
    ID3D12Resource* const P = b.upload.Get();
    const UINT gx = (UINT)(w + 7) / 8, gy = (UINT)(h + 7) / 8;
    std::vector<Pass> passes = {{"setup", {P, b.T.Get(), b.SF.Get(), b.SI.Get()}, (ntri + 63) / 64, 1},
        {"raster", {P, b.T.Get(), b.SF.Get(), b.SI.Get(), b.depth.Get(), b.pos.Get(), b.nrm.Get(), b.am.Get()}, gx, gy},
        {"motion", {P, b.pos.Get(), b.am.Get(), b.mot.Get()}, gx, gy},
        {"ssao", {P, b.pos.Get(), b.nrm.Get(), b.am.Get(), b.ss.Get()}, gx, gy}};
    if (opts.rtao) passes.push_back({"rtao", {P, b.T.Get(), b.pos.Get(), b.nrm.Get(), b.am.Get(), b.rt.Get()}, gx, gy});
    passes.push_back({"shade", {P, b.nrm.Get(), b.am.Get(), opts.rtao ? b.rt.Get() : b.ss.Get(), b.frame.Get(), b.hdr.Get()}, gx, gy});
    ID3D12Resource* const chan[kChannels] = {b.depth.Get(), b.pos.Get(), b.nrm.Get(), b.am.Get(), b.mot.Get(),
                                             b.ss.Get(), b.rt.Get(), b.frame.Get(), b.hdr.Get()};
    std::vector<std::pair<ID3D12Resource*, uint64_t>> reads;
    uint64_t total = 0;
    for (int i = 0; i < kChannels; ++i){ reads.push_back({chan[i], readBytes(i, w, h, opts.rtao, frameOnly)}); total += reads.back().second; }
    if (!dev.buffer(total, D3D12_HEAP_TYPE_READBACK, b.readback, err)) return false;
    ID3D12GraphicsCommandList* cl = dev.begin(err);
    if (!cl || !record(cl, b, trisBytes, passes, reads, err) || !dev.submitAndWait(err)) return false;
    const unsigned char* bytes = nullptr;
    D3D12_RANGE range{0, (SIZE_T)total};
    HRESULT hr = b.readback->Map(0, &range, (void**)&bytes);
    if (FAILED(hr)){ err = hrError("readback Map", hr); return false; }
    const float* f[kChannels]; uint64_t off = 0;
    for (int i = 0; i < kChannels; ++i){ f[i] = reads[i].second ? (const float*)(bytes + off) : nullptr; off += reads[i].second; }
    unpackFrame(r, f, w, h, vp, opts, frameOnly);
    D3D12_RANGE none{0, 0};
    b.readback->Unmap(0, &none);
    return true;
}
