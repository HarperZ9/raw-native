// The native D3D12 backend. The compute passes are the WGSL passes translated to
// HLSL by scripts/wgsl_to_hlsl.py (src/gpu/hlsl/) and compiled to DXIL by the
// Windows SDK's DXC at build time; this file only needs d3d12.dll and dxgi.dll.
// Every pass binds its buffers as root descriptors (root parameter i is WGSL
// binding i), so no descriptor heaps are needed. One command list records the
// whole frame: upload, six dispatches with UAV barriers between them, and the
// copies into one read-back buffer.
