def translate_all(read):
    """Every generated file: the renderer's passes, then the Threads module, whose
    shared code is everything in threads.wgsl before its first pass marker."""
    files = translate(read(GPU / "common.wgsl"), read(GPU / "passes.wgsl"))
    text = read(GPU / THREADS)
    i = text.find("//@pass ")
    files.update(translate(text[:i], text[i:], THREADS_LAYOUT, "threads_passes", THREADS_HEADER))
    cube = read(GPU / CUBE)
    for name, layout, ns, header in ((PBR, PBR_LAYOUT, "pbr_passes", PBR_HEADER), (LIGHT, LIGHT_LAYOUT, "light_passes", LIGHT_HEADER)):
        text = read(GPU / name)
        i = text.find("//@pass ")
        files.update(translate(cube + "\n" + text[:i], text[i:], layout, ns, header))
    text = read(GPU / SHADOW)
    i = text.find("//@pass ")
    files.update(translate(text[:i], text[i:], SHADOW_LAYOUT, "shadow_passes", SHADOW_HEADER))
    text = read(GPU / POST)
    i = text.find("//@pass ")
    files.update(translate(text[:i], text[i:], POST_LAYOUT, "post_passes", POST_HEADER))
    text = read(GPU / SWR)
    i = text.find("//@pass ")
    files.update(translate(text[:i], text[i:], SWR_LAYOUT, "swr_passes", SWR_HEADER))
    text = read(GPU / RT)
    i = text.find("//@pass ")
    files.update(translate(text[:i], text[i:], RT_LAYOUT, "rt_passes", RT_HEADER))
    files.update(translate_raster(read(GPU / RASTER)))
    return files


def selftest():
    """The translator must refuse what it cannot translate faithfully."""
    head = "struct Params {\n    w: u32,\n}\n"
    bind = "@group(0) @binding(0) var<uniform> P: Params;\n"
    body = "@compute @workgroup_size(8, 8)\nfn main(@builtin(global_invocation_id) gid: vec3u) {\n    %s\n}\n"
    refused = {"untyped let": "//@pass t\n" + bind + body % "let x = 1.0;",
               "untyped var": "//@pass t\n" + bind + body % "var y = 0u;",
               "HLSL keyword": "//@pass t\n" + bind + body % "let sample: f32 = 1.0;",
               "binding out of order": "//@pass t\n" + bind.replace("binding(0)", "binding(1)") + body % "return;"}
    for what, src in refused.items():
        try:
            translate(head, src)
        except TranslateError:
            continue
        print(f"selftest: accepted {what}", file=sys.stderr)
        return 1
    out = translate(head, "//@pass t\n" + bind + body % "let v: vec3f = vec3f(select(0.0, 1.0, P.w > 0u));")["t.hlsl"]
    want = "const float3 v = ((float3)(((P.w > 0u) ? (1.0f) : (0.0f))));"
    if want not in out:
        print("selftest: splat and select translated wrong:\n" + out, file=sys.stderr)
        return 1
    store = "@group(0) @binding(1) var<storage, read_write> acc: array<atomic<u32>>;\n"
    out = translate(head, "//@pass t\n" + bind + store + body % "atomicAdd(&acc[P.w], u32(mix(0.0, fract(2.5), 0.5)));")["t.hlsl"]
    if "InterlockedAdd(acc[P.w], uint(lerp(0.0f, frac(2.5f), 0.5f)));" not in out or "RWStructuredBuffer<uint> acc" not in out:
        print("selftest: atomics, mix or fract translated wrong:\n" + out, file=sys.stderr)
        return 1
    out = translate(head, "//@pass t\n" + bind + body % "let v: vec2f = vec2f(2.0 * select(1.0, 2.0, P.w >= 2u), 3.0);")["t.hlsl"]
    if "float2(2.0f * ((P.w >= 2u) ? (2.0f) : (1.0f)), 3.0f)" not in out:
        print("selftest: a comparison inside a constructor hid its comma:\n" + out, file=sys.stderr)
        return 1
    for what, stmt in {"pack4x8unorm": "let v: u32 = pack4x8unorm(vec4f(1.0));",
                       "atomicAdd as a value": "let v: u32 = atomicAdd(&acc[0u], 1u);",
                       "round (WGSL rounds half to even)": "let v: f32 = round(0.5);"}.items():
        try:
            translate(head, "//@pass t\n" + bind + store + body % stmt)
        except TranslateError:
            continue
        print(f"selftest: accepted {what}", file=sys.stderr)
        return 1
    rhead = "//@raster r\n@group(0) @binding(0) var t: texture_2d<f32>;\n@group(0) @binding(1) var s: sampler;\n"
    vs = "@vertex\nfn vs(@builtin(vertex_index) i: u32) -> @builtin(position) vec4f {\n    return vec4f(0.0);\n}\n"
    fs = "@fragment\nfn fs(@builtin(position) q: vec4f) -> @location(0) vec4f {\n    return textureSampleLevel(t, s, q.xy, 0.0);\n}\n"
    out = translate_raster(rhead + vs + fs)["r.hlsl"]
    for want in ("Texture2D<float4> t : register(t0);", "SamplerState s : register(s0);",
                 "float4 vs(uint i : SV_VertexID) : SV_Position {", "float4 fs(float4 q : SV_Position) : SV_Target0 {",
                 "return t.SampleLevel(s, q.xy, 0.0f);"):
        if want not in out:
            print(f"selftest: raster translation lacks {want!r}:\n" + out, file=sys.stderr)
            return 1
    for what, src in {"fragment returning a builtin": rhead + vs + fs.replace("@location(0) vec4f", "@builtin(position) vec4f"),
                      "writable storage in a raster pass": rhead.replace("var t: texture_2d<f32>", "var<storage, read_write> t: array<f32>") + vs + fs,
                      "textureSample with derivatives": rhead + vs + fs.replace("textureSampleLevel(t, s, q.xy, 0.0)", "textureSample(t, s, q.xy)"),
                      "entry points in the wrong order": rhead + fs + vs}.items():
        try:
            translate_raster(src)
        except TranslateError:
            continue
        print(f"selftest: accepted {what}", file=sys.stderr)
        return 1
    loops = "@compute @workgroup_size(8, 8)\nfn main(@builtin(global_invocation_id) gid: vec3u) {\n    for (var k: u32 = 0u; k < 3u; k++) {\n    }\n    for (var k: u32 = 0u; k < 3u; k++) {\n    }\n}\n"
    try:
        translate(head, "//@pass t\n" + bind + loops)
        print("selftest: accepted a loop variable declared twice in one function", file=sys.stderr)
        return 1
    except TranslateError:
        pass
    # RHI version 3: vertex pulling, a vertex-output struct, flat interpolants, and several
    # fragment targets in a struct named *Targets.
    v3 = ("//@raster g\n@group(0) @binding(0) var<storage, read> pos: array<f32>;\n"
          "struct VsOut {\n    @builtin(position) clip: vec4f,\n    @location(0) n: vec3f,\n    @location(1) @interpolate(flat) id: u32,\n}\n"
          "struct GTargets {\n    @location(0) a: vec4f,\n    @location(1) b: vec4f,\n}\n"
          "@vertex\nfn vs(@builtin(vertex_index) i: u32) -> VsOut {\n    var o: VsOut;\n    o.clip = vec4f(pos[i], 0.0, 0.0, 1.0);\n    return o;\n}\n"
          "@fragment\nfn fs(v: VsOut) -> GTargets {\n    var t: GTargets;\n    t.a = v.clip;\n    return t;\n}\n")
    out = translate_raster(v3)["g.hlsl"]
    for want in ("RWStructuredBuffer<float> pos : register(u0);", "float4 clip : SV_Position;", "float3 n : TEXCOORD0;",
                 "nointerpolation uint id : TEXCOORD1;", "float4 b : SV_Target1;", "VsOut o = (VsOut)0;", "GTargets fs(VsOut v) {"):
        if want not in out:
            print(f"selftest: RHI v3 raster translation lacks {want!r}:\n" + out, file=sys.stderr)
            return 1
    print("wgsl_to_hlsl: selftest passed")
    return 0


def main(argv):
    if "--selftest" in argv:
        return selftest()
    check = "--check" in argv
    read = lambda p: p.read_text(encoding="utf-8").replace("\r\n", "\n")
    try:
        files = translate_all(read)
    except TranslateError as e:
        print(f"wgsl_to_hlsl: {e}", file=sys.stderr)
        return 2
    stale = []
    for name, text in files.items():
        path = (GPU if name.endswith(".hpp") else OUT) / name
        old = read(path) if path.exists() else None
        if old != text:
            stale.append(name)
            if not check:
                OUT.mkdir(parents=True, exist_ok=True)
                path.write_bytes(text.encode("utf-8"))
    extra = sorted(p.name for p in OUT.glob("*") if p.name not in files or p.name == LAYOUT) if OUT.exists() else []
    if check:
        if stale or extra:
            print("wgsl_to_hlsl: generated HLSL is out of date with the WGSL: "
                  + ", ".join(stale + [f"{e} (not generated)" for e in extra])
                  + "\nrun: python scripts/wgsl_to_hlsl.py", file=sys.stderr)
            return 1
        print(f"wgsl_to_hlsl: {len(files)} generated files match the WGSL")
        return 0
    print(f"wgsl_to_hlsl: wrote {len(stale)} of {len(files)} files" + (f"; unexpected files: {extra}" if extra else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
