#!/usr/bin/env python3
"""Generate the hardware ray-query path tracer (src/rhi/d3d12/hw_shaders/hw_pt.hlsl), stdlib only.

The source is the compute path tracer src/renderer/gpu/shaders/hlsl/pt_trace.hlsl, itself generated
from pt.wgsl. This script swaps exactly one function, `trace`, the stack traversal of our own BVH,
for an inline ray query (DXR tier 1.1) against a top-level acceleration structure at t0. Every other
line stays byte for byte, so the hardware tracer runs the same materials, sampling, random numbers
and accumulation as the compute tracer, and docs/hw-rt.md's equivalence contract compares only the
traversal. The output is committed so the build needs no Python; CI runs this with --check.

Usage: python scripts/hw_pt_hlsl.py [--check]
Exit 0 written or up to date, 1 out of date (--check), 2 the source no longer has the expected shape.
"""
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src/renderer/gpu/shaders/hlsl/pt_trace.hlsl"
OUT = ROOT / "src/rhi/d3d12/hw_shaders/hw_pt.hlsl"
SIGNATURE = "float4 trace(float3 o, float3 d, float tMax, bool anyHit) {\n"
ANCHOR = "RWStructuredBuffer<float> ACC : register(u7);\n"

# The nearest hit with t in [1e-4, tMax] (any hit when anyHit): x t, y u, z v, w triangle (-1 none).
# TMin 1e-4 is the compute tracer's hit floor (t > 1e-4). Barycentrics weight vertices b and c, as
# the compute tracer's u and v do; the primitive index is the triangle index of the packed scene.
RAY_QUERY = """float4 trace(float3 o, float3 d, float tMax, bool anyHit) {
    RayDesc r;
    r.Origin = o; r.Direction = d; r.TMin = 1e-4f; r.TMax = tMax;
    float4 best = float4(tMax, 0.0f, 0.0f, -1.0f);
    if (anyHit) {
        RayQuery<RAY_FLAG_FORCE_OPAQUE | RAY_FLAG_ACCEPT_FIRST_HIT_AND_END_SEARCH> q;
        q.TraceRayInline(SCENE, RAY_FLAG_NONE, 0xFF, r);
        q.Proceed();
        if (q.CommittedStatus() == COMMITTED_TRIANGLE_HIT) {
            const float2 bc = q.CommittedTriangleBarycentrics();
            best = float4(q.CommittedRayT(), bc.x, bc.y, float(q.CommittedPrimitiveIndex()));
        }
    } else {
        RayQuery<RAY_FLAG_FORCE_OPAQUE> q;
        q.TraceRayInline(SCENE, RAY_FLAG_NONE, 0xFF, r);
        q.Proceed();
        if (q.CommittedStatus() == COMMITTED_TRIANGLE_HIT) {
            const float2 bc = q.CommittedTriangleBarycentrics();
            best = float4(q.CommittedRayT(), bc.x, bc.y, float(q.CommittedPrimitiveIndex()));
        }
    }
    return best;
}
"""


def generate(text):
    if SIGNATURE not in text or ANCHOR not in text:
        raise ValueError("pt_trace.hlsl no longer has the trace signature or the ACC binding this script expects")
    start = text.index(SIGNATURE)
    end = text.index("\n}\n", start) + 3          # the function's closing brace at column 0
    body = text[:start] + RAY_QUERY + text[end:]
    body = body.replace(ANCHOR, ANCHOR + "RaytracingAccelerationStructure SCENE : register(t0);\n", 1)
    lines = body.split("\n")
    if not lines[0].startswith("// Generated by scripts/wgsl_to_hlsl.py"):
        raise ValueError("pt_trace.hlsl lost its generated header")
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    head = ("// Generated by scripts/hw_pt_hlsl.py from src/renderer/gpu/shaders/hlsl/pt_trace.hlsl. Do not edit.\n"
            f"// pt_trace.hlsl sha256 {digest}\n"
            "// The compute path tracer with its BVH traversal replaced by an inline ray query (SM 6.5,\n"
            "// DXR tier 1.1). NI and NB stay bound so the register layout matches pt_trace; trace ignores them.\n")
    return head + "\n".join(lines[1:])


def main(argv):
    try:
        out = generate(SRC.read_text(encoding="utf-8"))
    except ValueError as e:
        print(f"hw_pt_hlsl: {e}")
        return 2
    have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if "--check" in argv:
        if have != out:
            print("hw_pt_hlsl: src/rhi/d3d12/hw_shaders/hw_pt.hlsl is out of date; run python scripts/hw_pt_hlsl.py")
            return 1
        print("hw_pt_hlsl: up to date")
        return 0
    OUT.write_text(out, encoding="utf-8", newline="\n")
    print(f"hw_pt_hlsl: wrote {OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
