// Writes the painterly shaders' pigment tables (web/shaders/paint/pigments.mjs) into
// src/renderer/data/pigments.hpp for the C++ core (ADR 0019, rule 4).
//   node tools/port/gen_pigments.mjs [--check]
// K_TAB, S_TAB and W_TAB are float64 in JavaScript (W_TAB comes from the CIE tables through
// spectral.mjs) and are written with the shortest decimal that round-trips, so the C++ reads the
// same doubles. The 17^3 latent lookup is f32 (it ships precomputed in lut-data.mjs) and is
// written the same way, each value exactly an f32. --check fails when the committed header differs
// from what the JavaScript gives today.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { K_TAB, S_TAB, W_TAB, LAMBDA, latentLut, LUT_N } from "../../web/shaders/paint/pigments.mjs";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "src", "renderer", "data", "pigments.hpp");
if (LAMBDA.length !== 31 || LUT_N !== 17) throw new Error("gen_pigments: the tables changed shape; update raw/renderer/style_image.hpp");
const lut = Array.from(latentLut());
if (lut.length !== 17 ** 3 * 4) throw new Error("gen_pigments: the latent lookup is not 17^3 x 4");
const all = Float64Array.from([...K_TAB.flat(), ...S_TAB.flat(), ...W_TAB.flat(), ...lut]);
const sha = createHash("sha256").update(Buffer.from(all.buffer)).digest("hex");
const f32 = (v) => { const s = String(v); return /[.e]/.test(s) ? s + "f" : s + ".0f"; };
const rows = (vals, per) => { const out = []; for (let i = 0; i < vals.length; i += per) out.push("    " + vals.slice(i, i + per).map(f32).join(", ") + ","); return out; };
const text = [
  "// Generated by tools/port/gen_pigments.mjs from web/shaders/paint/pigments.mjs. Do not edit.",
  `// K, S and W are float64; the latent lookup is f32 (each literal exact). sha256 of all values as f64 LE: ${sha}`,
  "#pragma once",
  "namespace raw::style::data {",
  "inline constexpr double kPigmentK[31][4] = {",
  ...K_TAB.map((r) => "    {" + r.map(String).join(", ") + "},"),
  "};",
  "inline constexpr double kPigmentS[31][4] = {",
  ...S_TAB.map((r) => "    {" + r.map(String).join(", ") + "},"),
  "};",
  "inline constexpr double kPigmentW[31][3] = {",
  ...W_TAB.map((r) => "    {" + r.map(String).join(", ") + "},"),
  "};",
  "inline constexpr float kLatentLut[17 * 17 * 17 * 4] = {",
  ...rows(lut, 8),
  "};",
  "}",
  "",
].join("\n");
if (process.argv.includes("--check")) {
  const old = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
  if (old !== text) { console.error("gen_pigments: src/renderer/data/pigments.hpp is out of date; run node tools/port/gen_pigments.mjs"); process.exit(1); }
  console.log(`gen_pigments: the committed tables match (sha256 ${sha})`);
} else {
  writeFileSync(OUT, text);
  console.log(`gen_pigments: wrote ${OUT} (sha256 ${sha})`);
}
