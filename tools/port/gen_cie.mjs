// Writes the CIE 1931 2-degree colour matching functions of web/shaders/cie1931.mjs into
// src/renderer/data/cie1931.hpp for the C++ core (ADR 0019, rule 4).
//   node tools/port/gen_cie.mjs [--check]
// The tables are float64 in JavaScript and are written with the shortest decimal that
// round-trips, so the C++ reads the same doubles. --check fails when the committed header differs
// from what the JavaScript gives today.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { CMF_START, CMF_STEP, CMF_N, CMF_X, CMF_Y, CMF_Z } from "../../web/shaders/cie1931.mjs";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "src", "renderer", "data", "cie1931.hpp");
if (CMF_START !== 380 || CMF_STEP !== 5 || CMF_N !== 81) throw new Error("gen_cie: the CMF table changed shape; update raw/renderer/style_spectral.hpp");
const all = Float64Array.from([...CMF_X, ...CMF_Y, ...CMF_Z]);
const sha = createHash("sha256").update(Buffer.from(all.buffer)).digest("hex");
const rows = (vals) => { const out = []; for (let i = 0; i < vals.length; i += 9) out.push("    " + Array.from(vals.slice(i, i + 9)).map(String).join(", ") + ","); return out; };
const text = [
  "// Generated by tools/port/gen_cie.mjs from web/shaders/cie1931.mjs. Do not edit.",
  `// CIE 1931 2-degree observer, 380 to 780 nm in 5 nm steps, float64. sha256 of X, Y, Z as f64 LE: ${sha}`,
  "#pragma once",
  "namespace raw::style::data {",
  "inline constexpr int kCmfStart = 380, kCmfStep = 5, kCmfN = 81;",
  "inline constexpr double kCmfX[81] = {", ...rows(CMF_X), "};",
  "inline constexpr double kCmfY[81] = {", ...rows(CMF_Y), "};",
  "inline constexpr double kCmfZ[81] = {", ...rows(CMF_Z), "};",
  "}",
  "",
].join("\n");
if (process.argv.includes("--check")) {
  const old = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
  if (old !== text) { console.error("gen_cie: src/renderer/data/cie1931.hpp is out of date; run node tools/port/gen_cie.mjs"); process.exit(1); }
  console.log(`gen_cie: the committed tables match (sha256 ${sha})`);
} else {
  writeFileSync(OUT, text);
  console.log(`gen_cie: wrote ${OUT} (sha256 ${sha})`);
}
