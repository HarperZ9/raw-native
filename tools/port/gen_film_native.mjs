// Prints the block of style_film_stocks.cpp that holds the named negatives' numbers, read from stocks.mjs, so the
// native port carries the JS numbers exactly (shortest round-trip doubles).
//   node tools/port/gen_film_native.mjs            print the block
//   node tools/port/gen_film_native.mjs --write    replace the block between its markers
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { FILM_LIBRARY } from "../../web/shaders/film/library.mjs";
import { NEGATIVES } from "../../web/shaders/film/stocks.mjs";

const v3 = (a) => `{${a.map(String).join(", ")}}`;
function block(neg, id, comment) {
  const N = NEGATIVES[neg], s = FILM_LIBRARY.stocks[id];
  const lines = [`    if (name == "${neg}") {`, `        // ${comment}`];
  if (s.spectral && ["R", "G", "B"].every((k) => s.spectral[k]?.hwhmL && s.spectral[k]?.hwhmR)) {
    ["R", "G", "B"].forEach((k, i) => lines.push(`        N.sens[${i}] = g2(${s.spectral[k].peak}, ${s.spectral[k].hwhmL}, ${s.spectral[k].hwhmR});`));
  } else {
    lines.push("        N.sens[0] = g2(650.2, 51.1, 15.0); N.sens[1] = g2(547.9, 25.1, 27.0); N.sens[2] = g2(401.8, 21.2, 73.7);");
  }
  const d = s.dyes && s.dyes.cyan && s.dyes.magenta && s.dyes.yellow ? [s.dyes.cyan, s.dyes.magenta, s.dyes.yellow] : [686, 539, 447];
  lines.push(`        N.prim[0] = g(${d[0]}, 100); N.prim[1] = g(${d[1]}, 85); N.prim[2] = g(${d[2]}, 90);`);
  lines.push(`        N.k = ${v3(N.k)}; N.span = ${v3(N.span)};`, `        N.x0 = ${v3(N.x0)};`);
  lines.push(`        N.grainUm = ${v3(N.grainUm)}; N.sigmaD48 = ${v3(N.sigmaD48)}; return N;`, "    }");
  return lines.join("\n");
}
const text = [
  "    N.dmin = 0.05; N.base = 0.1; N.interimage = 0.3;",
  "    // Generated by tools/port/gen_film_native.mjs: the logistic fits of the digitised curves (stocks.mjs NEGATIVES).",
  block("neg-500t", "kodak-5219", "Kodak H-1-5219t (2015), digitised."),
  block("neg-250d", "kodak-5207", "Kodak H-1-5207, digitised; dye peaks from the 500T sheet and grain recalled, as stocks.mjs lists."),
  "",
].join("\n");
if (process.argv.includes("--write")) {
  const p = fileURLToPath(new URL("../../src/renderer/style_film_stocks.cpp", import.meta.url));
  const s = readFileSync(p, "utf8");
  if (!s.includes("@@NATIVE@@")) throw new Error("no marker in style_film_stocks.cpp");
  writeFileSync(p, s.replace("@@NATIVE@@", text));
} else process.stdout.write(text);
