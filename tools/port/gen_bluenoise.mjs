// Writes the engine's 64 x 64 blue-noise ranks (web/shaders/dither/bluenoise.mjs, void and
// cluster) into src/renderer/data/bluenoise64.hpp for the C++ core (ADR 0019, rule 4).
//   node tools/port/gen_bluenoise.mjs [--check]
// The table is generated once from the JavaScript generator and committed: re-running the
// generator in C++ would make the ranks depend on each C library's exp() agreeing with V8's to
// the last bit, because the generator breaks ties by comparing energies. --check fails when the
// committed table differs from what the generator makes today.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { blueNoise64 } from "../../web/shaders/dither/bluenoise.mjs";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "src", "renderer", "data", "bluenoise64.hpp");
const ranks = Array.from(blueNoise64());
if (ranks.length !== 4096 || new Set(ranks).size !== 4096) throw new Error("gen_bluenoise: the ranks are not a permutation of 0..4095");
const sha = createHash("sha256").update(Buffer.from(Uint16Array.from(ranks).buffer)).digest("hex");
const rows = [];
for (let i = 0; i < 4096; i += 16) rows.push("    " + ranks.slice(i, i + 16).join(", ") + ",");
const text = [
  "// Generated by tools/port/gen_bluenoise.mjs from web/shaders/dither/bluenoise.mjs. Do not edit.",
  `// Ranks 0..4095 of the 64 x 64 void-and-cluster mask, row-major; sha256 of the u16 LE bytes ${sha}`,
  "#pragma once",
  "#include <cstdint>",
  "namespace raw::style::data {",
  "inline constexpr std::uint16_t kBlueNoise64[4096] = {",
  ...rows,
  "};",
  "}",
  "",
].join("\n");
if (process.argv.includes("--check")) {
  const old = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
  if (old !== text) { console.error("gen_bluenoise: src/renderer/data/bluenoise64.hpp is out of date; run node tools/port/gen_bluenoise.mjs"); process.exit(1); }
  console.log(`gen_bluenoise: the committed table matches (sha256 ${sha})`);
} else {
  writeFileSync(OUT, text);
  console.log(`gen_bluenoise: wrote ${OUT} (sha256 ${sha})`);
}
