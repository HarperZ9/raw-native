// Turns the measured film-stock table (film_stocks.json, built by the workstation's measured package
// from the manufacturers' data sheets) into web/shaders/film/library-data.mjs, the compact record the
// film shader reads. Only reduced numbers (logistic fits, peaks, half widths, 50% MTF frequencies) and
// their provenance are copied. The digitised curves stay in the private table, referenced here by its
// sha256 (tableSha256); so do the camera curves, whose source states no licence: a camera ships as the
// 3 x 3 matrix integrated from its curves. No data-sheet file and no local path travels into this repo.
//   node tools/shaders/film_library.mjs <film_stocks.json> [<shader_options.json>]
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { LAMBDA, rgbBasis } from "../../web/shaders/film/stocks.mjs";

const [, , filmPath, optPath] = process.argv;
if (!filmPath) { console.error("usage: node tools/shaders/film_library.mjs <film_stocks.json> [<shader_options.json>]"); process.exit(2); }
const raw = readFileSync(filmPath), src = JSON.parse(raw.toString("utf8"));
const tableSha256 = createHash("sha256").update(raw).digest("hex");
const r4 = (v) => (v == null ? null : Math.round(v * 1e4) / 1e4);

// Kodak's printed "Log H Ref" (normal exposure of an 18% grey, log lux-seconds) equals log10(14.4 / ISO)
// within 0.006 on all five Kodak Alaris sheets that print it (Portra 160, 400, 800, Ektar 100, Gold 200);
// a sheet without a printed reference uses that relation, and says so.
function grey(s) {
  if (s.facts?.log_h_ref != null) return { logH: s.facts.log_h_ref, source: "printed Log H Ref" };
  if (s.facts?.grey_logH != null) return { logH: s.facts.grey_logH, source: s.facts.grey_note || "read from the figure" };
  if (s.iso) return { logH: r4(Math.log10(14.4 / s.iso)), source: "log10(14.4 / ISO), the relation the printed Kodak references follow" };
  return null;
}

function stock(id, s) {
  const f = s.figures || {}, sens = f.sensitometry, sp = f.spectral_sensitivity, dy = f.dye_density, mt = f.mtf, gr = f.granularity;
  const files = s.provenance?.files || {};
  const at = Object.fromEntries(Object.entries(f).map(([k, v]) => [k, v.at ? { file: v.at.file, page: v.at.page, method: v.at.method || "vector digitisation" } : null]));
  const rec = {
    id, name: s.name, maker: s.maker, kind: s.kind, iso: s.iso ?? null, balance: s.balance ?? null, process: s.process ?? s.facts?.process ?? null,
    grey: grey(s),
    prov: { source: s.provenance?.status === "missing" ? "none" : `film/${id}`, status: s.provenance?.status, citation: s.provenance?.citation || "",
      licence: s.provenance?.licence || "", files, figures: at, why: s.why || null },
    missing: s.missing_figures || [],
  };
  if (sens) {
    const layers = Object.keys(sens.fit);
    rec.sensitometry = {
      xAxis: sens.x_axis, axisFit: sens.axis_fit, identification: sens.identification,
      fit: Object.fromEntries(layers.map((k) => [k, sens.fit[k]])),
      gamma: sens.gamma, dmin: sens.dmin, dmax: sens.dmax,
      ...(sens.columns_used != null ? { columnsUsed: sens.columns_used } : {}),
    };
  }
  if (sp?.layers) rec.spectral = Object.fromEntries(Object.entries(sp.layers).map(([k, v]) => [k, { peak: v.peak_nm, hwhmL: v.hwhm_left_nm, hwhmR: v.hwhm_right_nm, halfMax: v.half_max_nm }]));
  if (dy?.dyes) rec.dyes = Object.fromEntries(Object.entries(dy.dyes).map(([k, v]) => [k, v.peak_nm]));
  if (mt) rec.mtf50 = mt.f50_cyc_per_mm;
  if (gr?.at_net_density_1) rec.sigmaD48 = Object.fromEntries(Object.entries(gr.at_net_density_1).map(([k, v]) => [k, v.sigmaD]));
  if (s.unresolved_figures) rec.unresolved = s.unresolved_figures;
  if (s.facts?.diffuse_rms_granularity != null) rec.diffuseRms = s.facts.diffuse_rms_granularity;
  if (s.facts?.base) rec.base = { material: s.facts.base.material ?? null, thicknessUm: s.facts.base.thickness_um ?? null };
  if (s.facts?.halation_control) rec.halation = { stated: s.facts.halation_control, byEdition: s.facts.halation_control_by_edition || null };
  return rec;
}

const stocks = Object.fromEntries(Object.entries(src.stocks).map(([id, s]) => [id, stock(id, s)]));
const held = Object.fromEntries(Object.entries(src.held_not_digitised || {}).map(([k, v]) => [k, { why: v.why, files: v.files }]));
const data = { built: src.provenance.built, tableSha256, stocks, cinestill: src.cinestill, held };
let body = `// Generated by tools/shaders/film_library.mjs from the measured film-stock table (${src.provenance.built}).\n`
  + `// Do not edit by hand: re-run the generator. Each stock carries its own provenance (file, sha256, page, method).\n`
  + `export const FILM_LIBRARY = ${JSON.stringify(data)};\n`;
writeFileSync(fileURLToPath(new URL("../../web/shaders/film/library-data.mjs", import.meta.url)), body);
console.log(`stocks ${Object.keys(stocks).length}, held ${Object.keys(held).length}, ${body.length} bytes`);

if (optPath) {
  const o = JSON.parse(readFileSync(optPath, "utf8"));
  const pick = (r, keys) => Object.fromEntries(keys.filter((k) => r[k] !== undefined).map((k) => [k, r[k]]));
  const opts = {
    built: o.provenance.built,
    crt: { masks: o.crt.masks, phosphors: o.crt.phosphors, tubes: o.crt.tubes, modes: o.crt.modes,
      maskRecords: o.crt.mask_records.map((r) => pick(r, ["id", "product", "mask", "pitch_mm", "diagonal_in", "prov"])) },
    lens: { coatings: o.lens.coatings },
  };
  const glass = { prov: o.lens.glasses.prov, rows: o.lens.glasses.rows.map((r) => pick(r, ["id", "maker", "glass", "formula", "c", "range_um", "nd", "vd", "glass_code"])) };
  // One matrix per camera, integrated exactly as sensor.mjs documents; the curves stay in the private table.
  const basis = rgbBasis();
  const at = (arr, l) => { const i = (l - 400) / 10; return i < 0 || i > arr.length - 1 ? 0 : arr[Math.round(i)]; };
  const cams = { prov: o.sensor.cameras.prov, rows: o.sensor.cameras.rows.map((r) => {
    const M = new Array(9).fill(0);
    LAMBDA.forEach((l, w) => { const c = [at(r.r, l), at(r.g, l), at(r.b, l)]; for (let k = 0; k < 3; k++) for (let j = 0; j < 3; j++) M[k * 3 + j] += c[k] * basis[w][j]; });
    for (let k = 0; k < 3; k++) { const t = M[k * 3] + M[k * 3 + 1] + M[k * 3 + 2]; for (let j = 0; j < 3; j++) M[k * 3 + j] = Math.round(1e6 * M[k * 3 + j] / t) / 1e6; }
    return { id: r.id, camera: r.camera, matrix: M };
  }) };
  const head = (what) => `// Generated by tools/shaders/film_library.mjs from the measured shader-option table (${o.provenance.built}): ${what}.
`
    + `// Do not edit by hand. Every record carries prov (or inherits its table's); web/shaders/options.mjs refuses one without it.
`;
  const files = [["../../web/shaders/options-data.mjs", head("CRT and coating options") + `export const OPTION_DATA = ${JSON.stringify(opts)};
`],
    ["../../web/shaders/lens/glass-data.mjs", head("catalogue glasses") + `export const GLASS_DATA = ${JSON.stringify(glass)};
`],
    ["../../web/shaders/sensor-data.mjs", head("camera spectral sensitivities") + `export const CAMERA_DATA = ${JSON.stringify(cams)};
`]];
  for (const [f, b] of files) { writeFileSync(fileURLToPath(new URL(f, import.meta.url)), b); console.log(f, b.length, "bytes"); }
}
