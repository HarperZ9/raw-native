// Writes web/shaders/paint/lut-data.mjs: the pigment-latent lookup, solved by buildLut().
//   node tools/shaders/gen-paint-lut.mjs
import { writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { buildLut, LUT_N } from "../../web/shaders/paint/pigments.mjs";
const lut = buildLut(), b64 = Buffer.from(lut.buffer).toString("base64");
const sha = createHash("sha256").update(Buffer.from(lut.buffer)).digest("hex");
writeFileSync(new URL("../../web/shaders/paint/lut-data.mjs", import.meta.url),
  `// Generated by tools/shaders/gen-paint-lut.mjs: ${LUT_N}^3 x 4 Float32 pigment concentrations, sha256 ${sha}.\nexport const LUT_B64 = "${b64}";\n`);
console.log("wrote", lut.length, "floats, sha256", sha);
